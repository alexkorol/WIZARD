'use strict';

// Offline-only campaign forge. This file and core.js run under Node; neither is
// loaded by the shipped page. Re-run intentionally when preparing a new pack.

var fs = require('fs');
var path = require('path');
var Core = require('./core.js');

var PACK_SEED = 'VERDIGRIS-VAULT-I';
var SOURCE_FLOORS = [
  1, 2, 3, 4, 5, 8, 12, 20, 40, 80, 100, 200,
  400, 800, 1600, 3200, 7000, 15000, 30000, 60000,
  100000, 250000, 600000, 999999
];

function difficultyKey(level) {
  var analysis = level.solution.analysis;
  return Math.log2((level.solution.states || 0) + 1) * 10 +
    level.solution.actions.length * 0.45 + analysis.interdependence * 1.4 +
    analysis.counterintuitive * 3 + analysis.goalEvictions * 5 +
    analysis.barrierBoxes * 4 + analysis.storageEntries * 1.5;
}

function strengthenOffline(level, sourceFloor) {
  if (level.boxes.length < 5) return;
  var budget = sourceFloor < 50000 ? 50000 : 100000;
  var started = Date.now();
  var result = Core.solve(level, { limit: budget });
  if (result.solved) {
    result.moves = Core.routeMoveCount(level, result.actions);
    result.moveOptimal = false;
    result.proof = 'offline-search';
    result.analysis = Core.analyzeSolution(level, result.actions);
    level.solution = result;
  } else {
    level.solution.states = result.states;
    level.solution.proof = 'offline-constructive';
    level.solution.optimal = false;
    level.solution.moveOptimal = false;
  }
  console.log('  oracle', result.solved ? 'solved' : 'resisted', result.states + '/' + budget,
    (Date.now() - started) + 'ms');
}

function serialize(level, sourceFloor) {
  var moves = Core.routeMoveCount(level, level.solution.actions);
  if (!Number.isFinite(moves) || moves !== level.solution.moves) {
    throw new Error('Invalid proof route at source floor ' + sourceFloor);
  }
  return {
    sourceFloor: sourceFloor,
    width: level.width,
    height: level.height,
    floor: Array.from(level.floor).sort(function (a, b) { return a - b; }),
    walls: Array.from(level.walls).sort(function (a, b) { return a - b; }),
    deadSquares: Array.from(Core.staticDeadSquares(level)).sort(function (a, b) { return a - b; }),
    goals: level.goals,
    boxes: level.boxes,
    player: level.player,
    rating: level.rating,
    difficultyKey: Math.round(difficultyKey(level) * 10) / 10,
    solution: {
      optimal: Boolean(level.solution.optimal),
      moveOptimal: Boolean(level.solution.moveOptimal),
      proof: level.solution.proof,
      pushes: level.solution.actions.length,
      moves: level.solution.moves,
      states: level.solution.states,
      actions: level.solution.actions,
      analysis: level.solution.analysis
    }
  };
}

function validateOrder(levels) {
  for (var index = 1; index < levels.length; index += 1) {
    if (levels[index].difficultyKey < levels[index - 1].difficultyKey) {
      throw new Error('Campaign difficulty decreased at stage ' + (index + 1));
    }
  }
}

function main() {
  var forged = SOURCE_FLOORS.map(function (sourceFloor) {
    var started = Date.now();
    var level = Core.generate(PACK_SEED, sourceFloor);
    strengthenOffline(level, sourceFloor);
    var serialized = serialize(level, sourceFloor);
    console.log('forged', sourceFloor, level.solution.actions.length + 'p',
      level.solution.states + ' states', (Date.now() - started) + 'ms');
    return serialized;
  });
  var tutorials = forged.slice(0, 4);
  var campaign = tutorials.concat(forged.slice(4).sort(function (a, b) {
    return a.difficultyKey - b.difficultyKey || a.sourceFloor - b.sourceFloor;
  }));
  validateOrder(campaign);
  campaign.forEach(function (level, index) {
    level.stage = index + 1;
    level.id = 'vault-' + String(index + 1).padStart(2, '0');
  });
  var payload = {
    version: 1,
    id: 'verdigris-vault-i',
    name: 'Vault I',
    title: 'The Verdigris Vault',
    levels: campaign
  };
  var output = '/* Generated by forge-campaign.js. Do not edit by hand. */\n' +
    '(function (root) {\n  root.SokobanCampaign = ' + JSON.stringify(payload) + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
  fs.writeFileSync(path.join(__dirname, 'levels.js'), output);
  console.log('Wrote ' + campaign.length + ' validated stages to levels.js');
}

main();
